"""Compile only the four versioned KD cards into the report-specific package."""
from pathlib import Path
import json
import subprocess
ROOT = Path(__file__).resolve().parents[1]
NAMES = ("Botnet", "C2", "NetworkActivity", "Phishing")
files = list((ROOT / "KD").iterdir())
assert len(files) == 4 and {p.name for p in files} == {n + ".md" for n in NAMES}
lines = ["// Code generated by tools/generate_report_knowledge.py; DO NOT EDIT.", "package service", "", "var reportKnowledgeSources = map[string]string{"]
for name in NAMES:
    text = (ROOT / "KD" / (name + ".md")).read_text(encoding="utf-8")
    assert "KD-v0.2" in text
    lines.append(json.dumps(name) + ": " + json.dumps(text, ensure_ascii=False) + ",")
lines.append("}")
target = ROOT / "vulnscan-backend/traffic/internal/service/report_knowledge_generated.go"
target.write_text("\n".join(lines) + "\n", encoding="utf-8")
subprocess.run(["gofmt", "-w", str(target)], check=True)
